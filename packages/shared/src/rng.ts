import type { Rng } from "./types.js";

/**
 * Small deterministic PRNG (mulberry32). Used wherever a reproducible random
 * source is needed: engine self-tests, AI tie-breaking in tests, replays.
 */
export function seededRng(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
